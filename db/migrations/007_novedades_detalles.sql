-- 007_novedades_detalles.sql: per-type details of a novedad (`detalles` jsonb) and two more support files
-- (historia clinica for incapacidades, soporte for permisos).
-- Apply manually in the Supabase SQL editor AFTER 006, then run db/verification/007_novedades_detalles_verify.sql.
-- Idempotent where practical. Only the backend (service role) touches these objects: RLS stays on, no policies.
--
-- What changes:
--   * detalles jsonb NOT NULL DEFAULT '{}': the API validates its shape per tipo/subtipo (zod). Rows created before
--     this migration simply get '{}' and stay valid; the DB only guarantees that it is a JSON object.
--   * historia_path / soporte_path (nullable): storage object paths in the same private bucket as 006
--     (yyyy/mm/<uuid>-historia.<ext> and yyyy/mm/<uuid>-soporte.<ext>, never URLs), unique per novedad.
--   * novedades_arl_chk is RELAXED: the 006 version forbade any adjunto outside ARL, but every incapacidad (also
--     "Enfermedad general") now carries one. ARL still requires adjunto + firma + responsable; the firma stays ARL-only.
--   * novedades_files_chk ties historia to Incapacidades and soporte to Permisos / Permisos academicos.
--
-- Nothing here can reject an existing row: the new columns start empty, the relaxed check accepts everything the 006
-- one accepted, and no CHECK looks inside `detalles` (per-type rules live in the API, so legacy rows stay editable).
--
-- DEPLOY: apply this and deploy the backend back to back (the new backend selects/writes the new columns).
-- ROLLBACK: see db/migrations/rollback/007_novedades_detalles.down.sql (destroys detalles and the two new file paths).

-- ---------------------------------------------------------------------------
-- 1. New columns.
-- ---------------------------------------------------------------------------
alter table novedades add column if not exists detalles jsonb not null default '{}'::jsonb;
alter table novedades add column if not exists historia_path text;
alter table novedades add column if not exists soporte_path text;

alter table novedades drop constraint if exists novedades_detalles_chk;
alter table novedades add constraint novedades_detalles_chk check (jsonb_typeof(detalles) = 'object');

-- ---------------------------------------------------------------------------
-- 2. ARL check relaxed: the adjunto is no longer ARL-only (any Incapacidades row may have one).
-- ---------------------------------------------------------------------------
alter table novedades drop constraint if exists novedades_arl_chk;
alter table novedades add constraint novedades_arl_chk check (
  (coalesce(subtipo, '') = 'ARL' and adjunto_path is not null and firma_path is not null and responsable_id is not null)
  or (coalesce(subtipo, '') <> 'ARL' and firma_path is null and (adjunto_path is null or tipo = 'Incapacidades')));

-- historia -> Incapacidades only; soporte -> Permisos and Permisos académicos only.
alter table novedades drop constraint if exists novedades_files_chk;
alter table novedades add constraint novedades_files_chk check (
  (historia_path is null or tipo = 'Incapacidades')
  and (soporte_path is null or tipo in ('Permisos', 'Permisos académicos')));

-- Paths are generated by the API: yyyy/mm/<uuid>-historia.<ext> and yyyy/mm/<uuid>-soporte.<ext> (same shape as 006).
alter table novedades drop constraint if exists novedades_extra_paths_chk;
alter table novedades add constraint novedades_extra_paths_chk check (
  (historia_path is null or historia_path ~ '^[0-9]{4}/(0[1-9]|1[0-2])/[0-9a-f]{8}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{12}-historia\.(pdf|png|jpg|webp)$')
  and (soporte_path is null or soporte_path ~ '^[0-9]{4}/(0[1-9]|1[0-2])/[0-9a-f]{8}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{12}-soporte\.(pdf|png|jpg|webp)$'));

-- One storage object can belong to a single novedad (a path is generated per upload).
create unique index if not exists novedades_historia_path_key on novedades (historia_path) where historia_path is not null;
create unique index if not exists novedades_soporte_path_key on novedades (soporte_path) where soporte_path is not null;
