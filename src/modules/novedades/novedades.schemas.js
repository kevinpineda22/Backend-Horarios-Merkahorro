import { z } from "zod";
import { toEpochDay } from "../sugerido/domain/dates.js";
import { isValidCedula, normalizeCedula } from "../../shared/cedula.js";
import {
  ALL_SUBTIPOS,
  NOVEDAD_CREATABLE_TYPES,
  NOVEDAD_TYPES,
  validateNovedadRules,
} from "./domain/novedadTypes.js";
import {
  ALLOWED_MIME_TYPES,
  FILE_KINDS,
  MAX_FILE_BYTES,
  isAllowedContentType,
  isValidObjectPath,
} from "./domain/novedadFiles.js";
import { validateDetalles } from "./domain/novedadDetalles.js";

const required = (label) => ({ required_error: `${label} es obligatorio` });

// Real calendar date as 'YYYY-MM-DD' (rejects 2026-02-30 and datetime strings).
const dateOnly = z.string(required("La fecha")).refine(
  (v) => {
    try {
      toEpochDay(v);
      return true;
    } catch {
      return false;
    }
  },
  { message: "Fecha inválida (use AAAA-MM-DD)" },
);

// Reject anything but digits and formatting separators (letters signal a typo), then apply the
// company-wide normalization (digits only, leading zeros stripped) and require 5-15 digits.
const cedula = z
  .string(required("La cédula"))
  .refine((v) => /^[0-9\s.,-]*$/.test(v), { message: "Cédula inválida (5 a 15 dígitos)" })
  .transform(normalizeCedula)
  .refine(isValidCedula, { message: "Cédula inválida (5 a 15 dígitos)" })
  // All zeros survives normalization but can never match a real employee.
  .refine((v) => !/^0+$/.test(v), { message: "Cédula inválida (5 a 15 dígitos)" });

// Normalize to NFC so "Día" sent in decomposed form (NFD) matches the canonical label.
const nfc = (v) => (typeof v === "string" ? v.normalize("NFC") : v);
const tipoError = { errorMap: () => ({ message: "Tipo de novedad inválido" }) };
// Reads and filters accept every stored tipo (history included); writes only the current ones.
const tipo = z.preprocess(nfc, z.enum(NOVEDAD_TYPES, tipoError));
const tipoWritable = z.preprocess(nfc, z.enum(NOVEDAD_CREATABLE_TYPES, tipoError));

const subtipo = z.enum(ALL_SUBTIPOS, { errorMap: () => ({ message: "Subtipo de novedad inválido" }) }).nullable();

// Raw SIESA sede text for employees whose sede is not one of the stores.
const sedeNombre = z
  .string()
  .transform((v) => v.replace(/\s+/g, " ").trim())
  .refine((v) => v.length <= 120, { message: "La sede no puede superar 120 caracteres" })
  .nullable()
  .transform((v) => (v === "" ? null : v));

// Storage object paths generated by POST /uploads; anything else is rejected.
const objectPath = (kind) =>
  z.string().refine((v) => isValidObjectPath(kind, v), { message: "Ruta de archivo inválida" }).nullable();

const observacion = z
  .string()
  .max(1000, "La observación no puede superar 1000 caracteres")
  .nullable()
  .transform((v) => (v == null || v.trim() === "" ? null : v.trim()));

// Per-type details: the shape is validated per tipo (domain/novedadDetalles.js) once the tipo is known.
const detalles = z.record(z.unknown(), { invalid_type_error: "detalles debe ser un objeto" });

const sedeId = z.string().min(1, "Sede inválida").nullable();

const rangeOk = (d) => !d.fechaInicio || !d.fechaFin || d.fechaFin >= d.fechaInicio;
const rangeIssue = { message: "fechaFin no puede ser anterior a fechaInicio", path: ["fechaFin"] };

export const createNovedadSchema = z
  .object({
    cedula,
    tipo: tipoWritable,
    subtipo: subtipo.optional().default(null),
    fechaInicio: dateOnly,
    fechaFin: dateOnly,
    observacion: observacion.optional().default(null),
    sedeId: sedeId.optional().default(null),
    sedeNombre: sedeNombre.optional().default(null),
    adjuntoPath: objectPath("adjunto").optional().default(null),
    firmaPath: objectPath("firma").optional().default(null),
    historiaPath: objectPath("historia").optional().default(null),
    soportePath: objectPath("soporte").optional().default(null),
    detalles: detalles.optional().default({}),
  })
  .refine(rangeOk, rangeIssue)
  .superRefine((d, ctx) => {
    for (const { path, message } of validateNovedadRules(d)) ctx.addIssue({ code: "custom", path: [path], message });
    for (const { path, message } of validateDetalles(d).issues) {
      ctx.addIssue({ code: "custom", path: path.split(".").map((p) => (/^\d+$/.test(p) ? Number(p) : p)), message });
    }
  })
  // Store the normalized details (trimmed text, optionals dropped, days sorted).
  .transform((d) => ({ ...d, detalles: validateDetalles(d).data }));

export const patchNovedadSchema = z
  .object({
    cedula,
    tipo: tipoWritable,
    subtipo,
    fechaInicio: dateOnly,
    fechaFin: dateOnly,
    observacion,
    sedeId,
    sedeNombre,
    adjuntoPath: objectPath("adjunto"),
    firmaPath: objectPath("firma"),
    historiaPath: objectPath("historia"),
    soportePath: objectPath("soporte"),
    detalles,
  })
  .partial()
  .refine((d) => Object.keys(d).length > 0, { message: "Debes enviar al menos un campo" })
  .refine(rangeOk, rangeIssue);

export const anularSchema = z.object({
  motivo: z
    .string(required("El motivo"))
    .transform((v) => v.trim())
    .refine((v) => v.length >= 1 && v.length <= 500, { message: "El motivo debe tener entre 1 y 500 caracteres" }),
});

export const listQuerySchema = z
  .object({
    sede: z.string().min(1).optional(),
    cedula: cedula.optional(),
    desde: dateOnly.optional(),
    hasta: dateOnly.optional(),
    tipo: tipo.optional(),
    incluirAnuladas: z
      .enum(["true", "false"])
      .optional()
      .transform((v) => v === "true"),
  })
  .refine((q) => !q.desde || !q.hasta || q.hasta >= q.desde, {
    message: "hasta no puede ser anterior a desde",
    path: ["hasta"],
  });

export const uploadSchema = z
  .object({
    kind: z.enum(FILE_KINDS, { errorMap: () => ({ message: "Tipo de archivo inválido" }) }),
    fileName: z.string(required("El nombre del archivo")).min(1, "El nombre del archivo es obligatorio").max(255, "El nombre del archivo es demasiado largo"),
    contentType: z.enum(ALLOWED_MIME_TYPES, {
      errorMap: () => ({ message: "Formato no permitido (PDF, PNG, JPG o WEBP)" }),
    }),
    size: z
      .number(required("El tamaño"))
      .int("Tamaño inválido")
      .positive("El archivo está vacío")
      .max(MAX_FILE_BYTES, "El archivo supera el máximo de 10 MB"),
    sedeId: sedeId.optional().default(null),
  })
  .refine((d) => isAllowedContentType(d.kind, d.contentType), {
    message: "La firma debe ser una imagen PNG",
    path: ["contentType"],
  });

export const fileParamsSchema = z.object({
  id: z.string().uuid("Identificador inválido"),
  kind: z.enum(FILE_KINDS, { errorMap: () => ({ message: "Tipo de archivo inválido" }) }),
});

export const idParamSchema = z.object({ id: z.string().uuid("Identificador inválido") });
